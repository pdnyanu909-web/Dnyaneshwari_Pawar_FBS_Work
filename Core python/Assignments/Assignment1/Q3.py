#find quotient and remainder of two numbers
#  Take input
num1 = int(input('Enter num1:'))
num2 = int(input('Enter num2:'))

# perform floor division
Quotient = num1 // num2

# perform modulus
Remainder = num1 % num2
#Display result
print('Quotient:',Quotient)
print('Remainder:',Remainder)